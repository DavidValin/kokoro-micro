//! Mandarin front end.
//!
//! A port of misaki's `ZHG2P` legacy path - the one Kokoro-82M itself uses
//! (`kokoro/pipeline.py` constructs `ZHG2P(version=None)` for that repo), so
//! there is no paddlespeech frontend to reproduce:
//!
//! 1. Arabic numerals are spelled out as Chinese numerals.
//! 2. Full-width punctuation is folded onto the tokens the model knows.
//! 3. The text is split into Han and non-Han runs.
//! 4. Han runs are segmented with jieba, and each word is read as pinyin -
//!    from a phrase dictionary where one exists, per character otherwise.
//! 5. Each syllable becomes IPA, with the tone as one of `→ ↗ ↓ ↘`.
//!
//! Step 4 is where the phrase dictionary earns its keep. Character-by-character
//! readings get heteronyms wrong in ways that are immediately audible to a
//! native speaker - 银行 "bank" reads as *yínxíng* rather than *yínháng*, 长江
//! "Yangtze" as *zhǎngjiāng* rather than *chángjiāng* - so words are looked up
//! whole first.
//!
//! Following misaki, no tone sandhi is applied: third-tone and 一/不 sandhi are
//! left to the model, matching what the voices were trained on.

use std::collections::HashMap;
use std::sync::OnceLock;

use super::zh_syllables::SYLLABLES;

/// word -> space-separated pinyin syllables with tone digits (neutral = 5).
/// Generated by `tools/gen_zh_data.py` from pypinyin's phrase dictionary.
const PHRASES_TSV: &str = include_str!("zh_phrases.txt");

fn phrases() -> &'static HashMap<&'static str, &'static str> {
    static PHRASES: OnceLock<HashMap<&'static str, &'static str>> = OnceLock::new();
    PHRASES.get_or_init(|| {
        PHRASES_TSV
            .lines()
            .filter_map(|line| line.split_once('\t'))
            .collect()
    })
}

fn jieba() -> &'static jieba_rs::Jieba {
    static JIEBA: OnceLock<jieba_rs::Jieba> = OnceLock::new();
    JIEBA.get_or_init(jieba_rs::Jieba::new)
}

fn is_han(c: char) -> bool {
    matches!(c, '\u{3400}'..='\u{4dbf}' | '\u{4e00}'..='\u{9fff}' | '\u{f900}'..='\u{faff}')
}

// --- numbers ---------------------------------------------------------------

const DIGITS: [char; 10] = ['零', '一', '二', '三', '四', '五', '六', '七', '八', '九'];
/// Positions inside a four-digit group.
const SMALL_UNITS: [&str; 4] = ["", "十", "百", "千"];
/// Group separators, every four digits.
const BIG_UNITS: [&str; 5] = ["", "万", "亿", "万亿", "亿亿"];

/// One group of at most four digits, e.g. `2035` -> `二千零三十五`.
fn group_to_chinese(group: &[u8]) -> String {
    let mut out = String::new();
    let len = group.len();
    let mut pending_zero = false;
    for (i, &d) in group.iter().enumerate() {
        let unit = SMALL_UNITS[len - 1 - i];
        if d == 0 {
            pending_zero = !out.is_empty();
            continue;
        }
        if pending_zero {
            out.push('零');
            pending_zero = false;
        }
        // "一十" at the head of a number is said "十": 15 is 十五, not 一十五.
        if !(d == 1 && unit == "十" && out.is_empty()) {
            out.push(DIGITS[d as usize]);
        }
        out.push_str(unit);
    }
    out
}

fn integer_to_chinese(digits: &str) -> String {
    let digits = digits.trim_start_matches('0');
    if digits.is_empty() {
        return "零".to_string();
    }
    let bytes: Vec<u8> = digits.bytes().map(|b| b - b'0').collect();
    let groups: Vec<&[u8]> = {
        let mut groups = Vec::new();
        let mut end = bytes.len();
        while end > 0 {
            let start = end.saturating_sub(4);
            groups.push(&bytes[start..end]);
            end = start;
        }
        groups.reverse();
        groups
    };
    let n = groups.len();
    let mut out = String::new();
    for (i, group) in groups.iter().enumerate() {
        let text = group_to_chinese(group);
        let unit_index = n - 1 - i;
        if text.is_empty() {
            continue;
        }
        if !out.is_empty() && group[0] == 0 {
            out.push('零');
        }
        out.push_str(&text);
        if unit_index < BIG_UNITS.len() {
            out.push_str(BIG_UNITS[unit_index]);
        }
    }
    out
}

/// Spell out Arabic numerals, the way misaki runs `cn2an` before phonemizing.
///
/// Digits are not in the model's vocabulary, so anything left un-spelled is
/// silently dropped - a number that simply vanishes mid-sentence.
fn spell_numbers(text: &str) -> String {
    let chars: Vec<char> = text.chars().collect();
    let mut out = String::with_capacity(text.len());
    let mut i = 0;
    while i < chars.len() {
        if !chars[i].is_ascii_digit() {
            out.push(chars[i]);
            i += 1;
            continue;
        }
        let start = i;
        while i < chars.len() && chars[i].is_ascii_digit() {
            i += 1;
        }
        let int_part: String = chars[start..i].iter().collect();
        // A decimal point only counts when digits follow it.
        let mut frac_part = String::new();
        if i + 1 < chars.len() && chars[i] == '.' && chars[i + 1].is_ascii_digit() {
            i += 1;
            let frac_start = i;
            while i < chars.len() && chars[i].is_ascii_digit() {
                i += 1;
            }
            frac_part = chars[frac_start..i].iter().collect();
        }
        if out.ends_with('-') || out.ends_with('\u{2212}') {
            out.pop();
            out.push('负');
        }
        // Past the 万亿 range the grouping units run out, and a string that
        // long is an identifier rather than a quantity anyway - read it out
        // digit by digit.
        if int_part.len() > 12 {
            out.extend(int_part.bytes().map(|b| DIGITS[(b - b'0') as usize]));
        } else {
            out.push_str(&integer_to_chinese(&int_part));
        }
        if !frac_part.is_empty() {
            out.push('点');
            out.extend(frac_part.bytes().map(|b| DIGITS[(b - b'0') as usize]));
        }
    }
    out
}

// --- punctuation -----------------------------------------------------------

/// Port of `ZHG2P.map_punctuation`: full-width marks onto the model's tokens.
fn map_punctuation(text: &str) -> String {
    let mut out = String::with_capacity(text.len());
    for c in text.chars() {
        match c {
            '、' | '，' => out.push_str(", "),
            '。' | '．' => out.push_str(". "),
            '！' => out.push_str("! "),
            '：' => out.push_str(": "),
            '；' => out.push_str("; "),
            '？' => out.push_str("? "),
            '《' | '「' | '【' | '«' => out.push_str(" \u{201c}"),
            '》' | '」' | '】' | '»' => out.push_str("\u{201d} "),
            '（' => out.push_str(" ("),
            '）' => out.push_str(") "),
            '…' | '⋯' => out.push('…'),
            '—' | '－' | '–' => out.push('—'),
            _ => out.push(c),
        }
    }
    out.trim().to_string()
}

// --- syllables -------------------------------------------------------------

fn tone_mark(tone: u8) -> &'static str {
    match tone {
        1 => "\u{2192}", // →  high level
        2 => "\u{2197}", // ↗  rising
        3 => "\u{2193}", // ↓  dipping
        4 => "\u{2198}", // ↘  falling
        _ => "",         //    neutral
    }
}

/// `"hao3"` -> `"xau↓"`. Unknown syllables yield nothing rather than noise.
fn syllable_to_ipa(syllable: &str) -> Option<String> {
    let (base, tone) = match syllable.as_bytes().last() {
        Some(b) if b.is_ascii_digit() => (
            &syllable[..syllable.len() - 1],
            (b - b'0').clamp(1, 5),
        ),
        _ => (syllable, 5),
    };
    // pypinyin writes ü as v in some styles; the table is keyed on ü.
    let owned;
    let base = if base.contains('v') {
        owned = base.replace('v', "ü");
        owned.as_str()
    } else {
        base
    };
    let idx = SYLLABLES.binary_search_by(|(k, _)| (*k).cmp(base)).ok()?;
    Some(SYLLABLES[idx].1.replace('0', tone_mark(tone)))
}

/// Longest phrase the dictionary holds; bounds the greedy match below.
const MAX_PHRASE_CHARS: usize = 12;

/// Read one segmented word as pinyin syllables with tone digits.
///
/// jieba's segmentation and the phrase dictionary do not always agree - jieba
/// happily returns 长江大桥 as one token, which is not a dictionary entry - so
/// an unmatched word is greedily re-matched against the dictionary from the
/// left before falling back to per-character readings. Without that step the
/// fallback silently undoes the dictionary's work: 长 alone reads *zhǎng*, and
/// the Yangtze becomes the "Zhang river".
fn word_to_syllables(word: &str) -> Vec<String> {
    if let Some(entry) = phrases().get(word) {
        return entry.split(' ').map(str::to_string).collect();
    }

    let chars: Vec<char> = word.chars().collect();
    let mut out = Vec::with_capacity(chars.len());
    let mut i = 0;
    while i < chars.len() {
        let mut matched = 0;
        let limit = MAX_PHRASE_CHARS.min(chars.len() - i);
        for len in (2..=limit).rev() {
            let candidate: String = chars[i..i + len].iter().collect();
            if let Some(entry) = phrases().get(candidate.as_str()) {
                out.extend(entry.split(' ').map(str::to_string));
                matched = len;
                break;
            }
        }
        if matched == 0 {
            let single: String = chars[i..i + 1].iter().collect();
            out.extend(
                pinyin::to_pinyin_vec(single.as_str(), pinyin::Pinyin::with_tone_num_end)
                    .into_iter()
                    .map(str::to_string),
            );
            matched = 1;
        }
        i += matched;
    }
    out
}

fn han_run_to_ipa(run: &str) -> String {
    let mut words = Vec::new();
    for token in jieba().cut(run, false) {
        let ipa: String = word_to_syllables(token.word)
            .iter()
            .filter_map(|s| syllable_to_ipa(s))
            .collect();
        if !ipa.is_empty() {
            words.push(ipa);
        }
    }
    words.join(" ")
}

// --- entry point -----------------------------------------------------------

/// Mandarin text -> Kokoro phonemes.
pub(crate) fn phonemize(text: &str) -> String {
    let text = map_punctuation(&spell_numbers(text));

    let mut out = String::new();
    let mut han = String::new();
    let mut latin = String::new();

    fn flush_han(han: &mut String, out: &mut String) {
        if !han.is_empty() {
            let ipa = han_run_to_ipa(han);
            if !ipa.is_empty() {
                if !out.is_empty() && !out.ends_with(' ') {
                    out.push(' ');
                }
                out.push_str(&ipa);
            }
            han.clear();
        }
    }
    // Latin inside Chinese ("WiFi", "GDP") is read as English rather than
    // passed through as bare letters, which the model would spell out.
    fn flush_latin(latin: &mut String, out: &mut String) {
        if !latin.trim().is_empty() {
            let lang = super::Lang::AmericanEnglish;
            if let Ok(ipa) = super::espeak::phonemize(latin.trim(), lang.espeak_voices(), lang) {
                if !ipa.is_empty() {
                    if !out.is_empty() && !out.ends_with(' ') {
                        out.push(' ');
                    }
                    out.push_str(&ipa);
                }
            }
        }
        latin.clear();
    }

    for c in text.chars() {
        if is_han(c) {
            flush_latin(&mut latin, &mut out);
            han.push(c);
        } else if c.is_ascii_alphabetic() || c == '\'' {
            flush_han(&mut han, &mut out);
            latin.push(c);
        } else {
            flush_han(&mut han, &mut out);
            flush_latin(&mut latin, &mut out);
            if c.is_whitespace() {
                if !out.is_empty() && !out.ends_with(' ') {
                    out.push(' ');
                }
            } else {
                out.push(c);
            }
        }
    }
    flush_han(&mut han, &mut out);
    flush_latin(&mut latin, &mut out);
    out.trim().to_string()
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn syllable_table_is_sorted_for_binary_search() {
        assert!(SYLLABLES.windows(2).all(|w| w[0].0 < w[1].0));
    }

    #[test]
    fn tones_become_arrows_not_digits() {
        assert_eq!(syllable_to_ipa("ni3").as_deref(), Some("ni\u{2193}"));
        assert_eq!(syllable_to_ipa("hao3").as_deref(), Some("xau\u{2193}"));
        assert_eq!(syllable_to_ipa("ma1").as_deref(), Some("ma\u{2192}"));
        assert_eq!(syllable_to_ipa("ma2").as_deref(), Some("ma\u{2197}"));
        assert_eq!(syllable_to_ipa("ma4").as_deref(), Some("ma\u{2198}"));
        assert_eq!(syllable_to_ipa("ma5").as_deref(), Some("ma"));
        assert_eq!(syllable_to_ipa("le").as_deref(), Some("lɤ"));
    }

    #[test]
    fn phrase_dictionary_fixes_heteronyms() {
        // The whole point of carrying the phrase dictionary.
        assert_eq!(word_to_syllables("银行"), vec!["yin2", "hang2"]);
        assert_eq!(word_to_syllables("长江"), vec!["chang2", "jiang1"]);
        assert_eq!(word_to_syllables("重要"), vec!["zhong4", "yao4"]);
    }

    #[test]
    fn heteronyms_survive_jieba_over_segmenting() {
        // jieba returns this as a single token that is not a dictionary entry;
        // the greedy re-match must still find 长江 inside it.
        assert_eq!(
            word_to_syllables("长江大桥"),
            vec!["chang2", "jiang1", "da4", "qiao2"]
        );
    }

    #[test]
    fn phonemizes_a_sentence_into_vocabulary_characters() {
        let ps = phonemize("你好，世界。我们今天去公园散步，好吗？");
        assert!(ps.starts_with("ni\u{2193}xau\u{2193}"), "{ps}");
        assert!(ps.contains(','), "comma should survive: {ps}");
        assert!(ps.ends_with('?'), "question mark should survive: {ps}");
        assert!(
            !ps.chars().any(|c| c.is_ascii_digit()),
            "tone digits must never reach the model: {ps}"
        );
        let vocab = crate::vocab::vocab();
        let unknown: Vec<char> = ps.chars().filter(|c| !vocab.contains_key(c)).collect();
        assert!(unknown.is_empty(), "not in the model's vocabulary: {unknown:?}");
    }

    #[test]
    fn spells_out_numbers() {
        assert_eq!(integer_to_chinese("0"), "零");
        assert_eq!(integer_to_chinese("10"), "十");
        assert_eq!(integer_to_chinese("15"), "十五");
        assert_eq!(integer_to_chinese("100"), "一百");
        assert_eq!(integer_to_chinese("2035"), "二千零三十五");
        assert_eq!(integer_to_chinese("10000"), "一万");
        assert_eq!(spell_numbers("有3个"), "有三个");
        assert_eq!(spell_numbers("3.5"), "三点五");
    }

    #[test]
    fn numbers_reach_the_model_instead_of_vanishing() {
        let ps = phonemize("我有3个苹果。");
        assert!(!ps.is_empty());
        assert!(!ps.chars().any(|c| c.is_ascii_digit()), "{ps}");
    }

    #[test]
    fn full_width_punctuation_is_folded_onto_model_tokens() {
        assert_eq!(map_punctuation("你好，世界。"), "你好, 世界.");
        assert_eq!(map_punctuation("真的？"), "真的?");
    }
}
